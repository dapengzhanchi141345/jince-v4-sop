MARKET = os.path.join(ROOT, "..", ".codebuddy-plugin", "marketplace.json")


def bump_version(v):
    parts = v.split(".")
    while len(parts) < 3:
        parts.append("0")
    try:
        parts = [int(p) if p.isdigit() else 0 for p in parts]
    except Exception:
        return v
    parts[1] += 1
    parts[2] = 0
    return ".".join(str(p) for p in parts)


