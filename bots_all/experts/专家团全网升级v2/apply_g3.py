            d = json.load(open(pj, encoding="utf-8"))
            v = d.get("version", "1.0.0"); ps = v.split(".")
            if len(ps) == 3:
                ps[1] = str(int(ps[1]) + 1); ps[2] = "0"
            else:
                ps = [ps[0], "1", "0"]
            d["version"] = ".".join(ps)
